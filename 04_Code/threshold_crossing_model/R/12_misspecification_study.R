## 12_misspecification_study.R ---------------------------------------------
## Fills Section 5.3 ("Robustness to misspecification") of the manuscript.
##
## DESIGN. Data are generated under a departure from the working model; the
## WORKING model (piecewise-quadratic trajectory, Gaussian errors, single assay
## floor, schedule-conditional) is then fitted unchanged. Everything reported is
## therefore the cost of fitting the working model when it is wrong.
##
## SCENARIOS (one departure at a time, n = 150)
##   correct        reference: data from the working model
##   traj_monotone  smoother monotone decline (no quadratic upturn)
##   traj_exp       sharper exponential approach to an asymptote
##   threshold_m5   DMR threshold at -5.0 instead of -4.5
##   hetero_floor   patient-specific assay floors
##   heavy_t3       t3 measurement errors AND t3 random effects
##   informative    response-adaptive visit intensity
##
## OUTPUT
##   outputs/misspec_raw.csv      one row per replicate
##   outputs/misspec_summary.csv  bias / coverage / calibration + MCse
##   outputs/table_misspec.tex    LaTeX table for Section 5.3
##
## RUNTIME. USE_MCMC = TRUE is required for honest credible-interval coverage
## and is the slow path (~4 chains x 7 scenarios x N_REP fits). Start with
## N_REP = 5 and USE_MCMC = FALSE to verify the pipeline, then scale up.
## -------------------------------------------------------------------------

