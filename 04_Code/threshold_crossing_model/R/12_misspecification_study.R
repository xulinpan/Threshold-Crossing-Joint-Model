N_REP    <- 200      # manuscript target; use 5-10 for a smoke test
N_SIM    <- 150      # n per scenario, as stated in Section 5.3
USE_MCMC <- TRUE     # FALSE = fast MAP (no coverage); TRUE = HMC (coverage)
ADAPT    <- 0.99

## ---- 1. generators for each departure ------------------------------------
## Each returns a latent-trajectory function m(t, u0, u1); the fitted model
## always assumes the quadratic form, so any other shape is a misspecification.
traj_fun <- function(scen, p = TRUTH) {
  switch(scen,
    ## working model: beta0 + beta1*l + beta2*l^2
    correct = function(t, u0, u1) p$beta0 + p$beta1*ell(t) + p$beta2*ell(t)^2 + u0 + u1*ell(t),
    ## monotone decline: quadratic term removed, slope steepened to match depth
    traj_monotone = function(t, u0, u1) p$beta0 + (p$beta1 + 0.45)*ell(t) + u0 + u1*ell(t),
    ## exponential approach to an asymptote (sharper early decline, hard floor)
    traj_exp = function(t, u0, u1) {
      asy <- p$beta0 + p$beta1*1.6
      (p$beta0 - asy) * exp(-1.8 * t) + asy + u0 + u1*ell(t)
    },
    ## remaining scenarios keep the correct trajectory
    function(t, u0, u1) p$beta0 + p$beta1*ell(t) + p$beta2*ell(t)^2 + u0 + u1*ell(t)
  )
}

## heavy-tailed draws, scaled to the same SD as the Gaussian case
rt_scaled <- function(n, sd, df = 3) sd * rt(n, df) / sqrt(df/(df-2))

simulate_misspec <- function(scen, n, seed, p = TRUTH, p_bm = 0.90) {
  set.seed(seed)
  m_fun <- traj_fun(scen, p)
  cD    <- if (scen == "threshold_m5") -5.0 else C_D
  heavy <- scen == "heavy_t3"
  informative <- scen == "informative"

  long <- list(); pat <- vector("list", n)
  for (i in seq_len(n)) {
    ## random effects: Gaussian, or t3 under the heavy-tailed departure
    if (heavy) { u0 <- rt_scaled(1, p$tau0); u1 <- rt_scaled(1, p$tau1) }
    else       { u0 <- rnorm(1, 0, p$tau0);  u1 <- rnorm(1, 0, p$tau1) }
    Ci <- runif(1, 1.5, 7.0)

    ## patient-specific floor under the heterogeneous-floor departure
    cF_i <- if (scen == "hetero_floor") C_F + rnorm(1, 0, 0.35) else C_F

    ## visit times (reuse the informative-intensity scheme from 01_simulate_data.R)
    if (!informative) {
      t <- numeric(0); cur <- 0
      repeat { cur <- cur + rlnorm(1, log(0.55), 0.5); if (cur > Ci) break; t <- c(t, cur) }
    } else {
      w <- rnorm(1, 0, 0.5); d0 <- -0.7; d1 <- 0.35; d2 <- 0.2
      grid <- seq(1e-3, Ci, length.out = 50)
      lam_max <- max(exp(d0 + d1*(m_fun(grid,u0,u1)+4.5) + d2*ell(grid) + w))*1.2 + 1e-6
      t <- numeric(0); cur <- 0
      repeat {
        cur <- cur + rexp(1, lam_max); if (cur > Ci) break
        lam <- exp(d0 + d1*(m_fun(cur,u0,u1)+4.5) + d2*ell(cur) + w)
        if (runif(1) < lam/lam_max) t <- c(t, cur)
      }
    }
    if (length(t) == 0 || min(t) > 0.25) t <- c(runif(1, 0.02, 0.12), t)
    t <- sort(t)

    bm <- rbinom(length(t), 1, p_bm)
    mu <- m_fun(t, u0, u1) + p$beta_bm * bm
    ys <- if (heavy) mu + rt_scaled(length(t), p$sigma_y) else rnorm(length(t), mu, p$sigma_y)
    fl <- as.integer(ys <= cF_i)
    yobs <- ifelse(fl == 1, C_F, ys)   # lab always REPORTS the nominal floor

    dv <- which(yobs <= cD); delta <- as.integer(length(dv) > 0)
    edges <- c(0, t)
    if (delta == 1) { k <- dv[1]; L <- edges[k]; R <- edges[k+1] } else { L <- NA; R <- NA }

    long[[i]] <- data.frame(pid = i, t = t, ell = ell(t), y = yobs, floor = fl, bm = bm)
    pat[[i]]  <- data.frame(pid = i, delta = delta, L = L, R = R, Cend = Ci)
  }
  list(long = do.call(rbind, long), pat = do.call(rbind, pat), n = n)
}

## ---- 2. run ---------------------------------------------------------------
SCEN <- c("correct","traj_monotone","traj_exp","threshold_m5",
          "hetero_floor","heavy_t3","informative")
PARS <- c("alpha","b1","log_sigma","log_tau1")   # reported in Section 5.3
truth <- c(alpha = TRUTH$alpha, b1 = TRUTH$beta1,
           log_sigma = log(TRUTH$sigma_y), log_tau1 = log(TRUTH$tau1))

## fit_one() returns the Stan parameter names on their natural scales, whereas
## this study reports the time slope as b1 and the two SDs on the log scale.
## Extract with `[` (not `[[`) only after checking the name so a failed or
## incompatible fit becomes NA instead of raising "subscript out of bounds".
fit_reported_parameter <- function(fit, pn) {
  native_name <- c(alpha = "alpha", b1 = "beta1",
                   log_sigma = "sigma_y", log_tau1 = "tau1")[[pn]]
  get_named_number <- function(x, nm) {
    if (is.null(x) || is.null(names(x)) || !nm %in% names(x)) return(NA_real_)
    value <- unname(x[nm])
    if (length(value) != 1L || !is.numeric(value)) return(NA_real_)
    as.numeric(value)
  }

  est <- get_named_number(fit$est, native_name)
  se  <- get_named_number(fit$se, native_name)
  if (pn %in% c("log_sigma", "log_tau1")) {
    ## Delta-method SE on the log scale. MAP fits already return NA SEs.
    if (!is.finite(est) || est <= 0) return(c(est = NA_real_, se = NA_real_))
    se  <- if (is.finite(se)) se / est else NA_real_
    est <- log(est)
  }
  c(est = est, se = se)
}

res <- list(); row <- 0
for (sc in SCEN) {
  for (r in seq_len(N_REP)) {
    coh <- simulate_misspec(sc, N_SIM, seed = 7000 + 1000*match(sc, SCEN) + r)
    ## fit_one() is defined in 04_simulation_study.R / 02_fit_models.R and fits
    ## the WORKING model; USE_MCMC controls MAP vs HMC.
    fit <- tryCatch(fit_one(coh, exact = FALSE), error = function(e) NULL)
    row <- row + 1
    if (is.null(fit)) { res[[row]] <- data.frame(scen = sc, rep = r, conv = 0L); next }
    d <- data.frame(scen = sc, rep = r, conv = 1L,
                    brier = fit$brier %||% NA, cal_slope = fit$cal_slope %||% NA)
    for (pn in PARS) {
      stat <- fit_reported_parameter(fit, pn)
      est <- stat[["est"]]; se <- stat[["se"]]
      d[[paste0("est_", pn)]] <- est
      d[[paste0("cov_", pn)]] <- as.integer(!is.na(est) && !is.na(se) &&
                                  abs(est - truth[[pn]]) <= 1.96*se)
    }
    res[[row]] <- d
  }
  message("done: ", sc)
}
res <- do.call(plyr::rbind.fill, res)
write.csv(res, file.path(DIR_OUT, "misspec_raw.csv"), row.names = FALSE)

## ---- 3. aggregate with Monte Carlo standard errors ------------------------
mcse_prop <- function(x) { x <- x[!is.na(x)]; sqrt(mean(x)*(1-mean(x))/length(x)) }
agg <- do.call(rbind, lapply(split(res, res$scen), function(d) {
  k <- sum(d$conv == 1)
  out <- data.frame(scenario = d$scen[1], nrep = nrow(d), converged = k,
                    conv_rate = round(k/nrow(d), 3))
  for (pn in PARS) {
    e <- d[[paste0("est_", pn)]]; cv <- d[[paste0("cov_", pn)]]
    out[[paste0("bias_", pn)]]  <- round(mean(e, na.rm = TRUE) - truth[[pn]], 3)
    out[[paste0("mcse_", pn)]]  <- round(sd(e, na.rm = TRUE)/sqrt(sum(!is.na(e))), 3)
    out[[paste0("cov_", pn)]]   <- round(mean(cv, na.rm = TRUE), 3)
    out[[paste0("covmc_", pn)]] <- round(mcse_prop(cv), 3)
  }
  out$cal_slope <- round(mean(d$cal_slope, na.rm = TRUE), 3)
  out
}))
agg <- agg[match(SCEN, agg$scenario), ]
write.csv(agg, file.path(DIR_OUT, "misspec_summary.csv"), row.names = FALSE)
print(agg[, c("scenario","conv_rate","bias_alpha","cov_alpha","cov_b1","cov_log_sigma","cov_log_tau1")])

